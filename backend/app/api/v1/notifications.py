router = APIRouter(prefix="/notifications", tags=["notifications"])
logger = get_logger("api.notifications")

_SSE_HEADERS = {"Cache-Control": "no-cache", "X-Accel-Buffering": "no"}


class ParseRequest(BaseModel):
    text: str = Field(min_length=1, description="通知原文")


@router.post(
    "/parse",
    summary="流式解析通知（预览）",
    description=(
        "返回 `text/event-stream`。不做持久化，仅流式返回解析候选。事件顺序：增量 `tool` → "
        "`meta`（工具状态，未连接/越权为 rejected）→ `data`（候选）→ `done`。时间字段由可信快照+"
        f"确定性规则生成，不受工具调用影响。{LOGIN_REQUIRED}"
    ),
    responses=responses(401, 422, 503),
    response_class=StreamingResponse,
)
async def parse_notification_stream(
    body: ParseRequest,
    request: Request,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Preview-parse notification text as SSE (Task 7.2): tool events + meta.

    No persistence — the parsed candidates are streamed for preview. Time
    fields are generated by the trusted snapshot + deterministic rules and are
    not affected by tool calls or their statuses.
    """
    request_id = getattr(request.state, "request_id", "")

    async def event_gen():
        bind_request_id(request_id)
        try:
            async for evt in extract_notification_stream(
                body.text, owner_id=current_user.id, db=db
            ):
                yield sse_event(evt["event"], evt["data"])
        except ApiError as e:
            logger.warning("notification parse business error", code=e.code)
            yield sse_error(e.code, e.message)
        except Exception:
            logger.exception("notification parse stream failed")
            yield sse_error("INTERNAL_ERROR", "通知解析失败")

    return StreamingResponse(
        event_gen(), media_type="text/event-stream", headers=_SSE_HEADERS
    )


class IngestRequest(BaseModel):
    text: str = Field(min_length=1)
    owner_id: str = Field(min_length=1)
    group_id: str | None = None


class GroupPublishRequest(BaseModel):
    text: str = Field(min_length=1)


@router.post("/ingest")
async def ingest_notification(
    body: IngestRequest,
    request: Request,
    source: str = Depends(verify_source),
    db: AsyncSession = Depends(get_db),
):
    """Source-facing ingest endpoint. Authenticated by source shared secret."""
    service = NotificationService(db)
    notif, parsed = await service.ingest(
        raw_text=body.text,
        source=source,
        owner_id=body.owner_id,
        group_id=body.group_id,
    )
    return success_response(
        data={
            "id": notif.id,
            "status": notif.status.value,
            "candidates": parsed,
        },
        message="notification ingested",
        request_id=request.state.request_id,
    )


@router.get("")
async def list_notifications(
    request: Request,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    service = NotificationService(db)
    notifs = await service.repo.list_for_user(current_user.id)
    return success_response(
        data=[
            {
                "id": n.id,
                "source": n.source,
                "status": n.status.value,
                "raw_text": n.raw_text[:200],
            }
            for n in notifs
        ],
        request_id=request.state.request_id,
    )


@router.get("/{notification_id}")
async def get_notification(
    notification_id: str,
    request: Request,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    service = NotificationService(db)
    notif, parsed = await service.get(notification_id, current_user.id)
    return success_response(
        data={
            "id": notif.id,
            "source": notif.source,
            "status": notif.status.value,
            "raw_text": notif.raw_text,
            "candidates": parsed,
            "group_id": notif.group_id,
            "published": notif.published,
        },
        request_id=request.state.request_id,
    )


